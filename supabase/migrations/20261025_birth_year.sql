-- Age: only the birth year is kept. It decides who can be found by name: whoever may still be under 16 is found only
-- by the dancer ID or the QR code. Slovakia keeps the GDPR age of 16 (art. 8); under it a parent agrees at sign-up.
-- The app's rule (BirthYear.needsParentConsent) is the same: born after (this year − 17) may still be 15.

alter table public.profiles add column birth_year smallint check (birth_year between 1900 and 2100);

-- 1. The sign-up form sends the year; anything that is not a plausible year is left out rather than failing the sign-up.
create or replace function public.handle_user_platform_sync()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare
  v_platform text;
  v_last_platform text;
  v_client_type text;
  v_name text;
  v_app_version text;
  v_dance_role text;
  v_birth_year smallint;
begin
  v_platform      := left(coalesce(new.raw_user_meta_data->>'platform', 'ios'), 20);
  v_last_platform := left(coalesce(new.raw_user_meta_data->>'last_platform', v_platform), 20);
  v_client_type   := left(coalesce(new.raw_user_meta_data->>'client_type', 'ios_native'), 30);
  v_name          := left(btrim(coalesce(new.raw_user_meta_data->>'name',
                                         new.raw_user_meta_data->>'full_name',
                                         split_part(new.email, '@', 1))), 60);
  v_app_version   := left(new.raw_user_meta_data->>'app_version', 20);
  v_dance_role    := case when new.raw_user_meta_data->>'dance_role' = 'coach' then 'coach' else 'dancer' end;
  v_birth_year    := case when new.raw_user_meta_data->>'birth_year' ~ '^\d{4}$'
                           and (new.raw_user_meta_data->>'birth_year')::int
                               between 1900 and extract(year from now())::int
                          then (new.raw_user_meta_data->>'birth_year')::smallint end;

  insert into public.profiles (id, email, name, platform, last_platform, client_type, app_version,
                               last_sign_in_at, created_at, updated_at, dance_role, birth_year)
  values (new.id, new.email, v_name, v_platform, v_last_platform, v_client_type, v_app_version,
          coalesce(new.last_sign_in_at, now()), now(), now(), v_dance_role, v_birth_year)
  on conflict (id) do update set
    email = excluded.email,
    name = coalesce(profiles.name, excluded.name),
    last_platform = case when excluded.last_platform <> 'unknown' then excluded.last_platform else profiles.last_platform end,
    client_type   = case when excluded.client_type   <> 'unknown' then excluded.client_type   else profiles.client_type   end,
    app_version = coalesce(excluded.app_version, profiles.app_version),
    birth_year = coalesce(profiles.birth_year, excluded.birth_year),
    last_sign_in_at = coalesce(new.last_sign_in_at, now()),
    updated_at = now();   -- dance_role is deliberately not overwritten on later sign-ins

  return new;
end;
$function$;

-- 2. Once set, the year does not change (only the owner corrects it), so nobody becomes findable by changing it.
create or replace function public.protect_profile_privileged_columns()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
BEGIN
  -- Service role / postgres / auth triggers have no JWT user
  IF auth.uid() IS NULL THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    NEW.role := 'user';
    NEW.account_status := 'active';
    NEW.ban_reason := NULL;
    NEW.dancer_code := NULL;            -- generated by trg_zz_profiles_server_defaults
    RETURN NEW;
  END IF;

  IF public.is_app_owner() THEN
    RETURN NEW;
  END IF;

  IF NEW.role IS DISTINCT FROM OLD.role
     OR NEW.account_status IS DISTINCT FROM OLD.account_status
     OR NEW.ban_reason IS DISTINCT FROM OLD.ban_reason THEN
    RAISE EXCEPTION 'Zmena roly alebo stavu účtu nie je povolená.' USING ERRCODE = '42501';
  END IF;

  IF NEW.dancer_code IS DISTINCT FROM OLD.dancer_code AND OLD.dancer_code IS NOT NULL THEN
    RAISE EXCEPTION 'Dancer ID sa nedá meniť.' USING ERRCODE = '42501';
  END IF;

  IF NEW.invite_code IS DISTINCT FROM OLD.invite_code AND OLD.invite_code IS NOT NULL THEN
    RAISE EXCEPTION 'Kód pozvánky sa nedá meniť.' USING ERRCODE = '42501';
  END IF;

  IF NEW.email IS DISTINCT FROM OLD.email THEN
    RAISE EXCEPTION 'E-mail sa mení cez nastavenia účtu, nie cez profil.' USING ERRCODE = '42501';
  END IF;

  IF NEW.ksis_id IS DISTINCT FROM OLD.ksis_id THEN
    RAISE EXCEPTION 'Číslo z KSIS sa overuje v Súťažiach, do profilu sa nepíše.' USING ERRCODE = '42501';
  END IF;

  IF OLD.birth_year IS NOT NULL AND NEW.birth_year IS DISTINCT FROM OLD.birth_year THEN
    RAISE EXCEPTION 'Rok narodenia sa nedá zmeniť. Ak je zlý, napíš nám na podporu.' USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$function$;

-- 3. By name only whoever is 16 for sure; by the dancer ID everybody. An unknown year counts as under 16.
create or replace function public.search_dancers(query text)
returns table(id uuid, dancer_code text, full_name text, club text, avatar_url text)
language plpgsql security definer set search_path to 'public' as $function$
declare
  v_query text := replace(replace(replace(trim(query), '\', '\\'), '%', '\%'), '_', '\_');
begin
  if length(trim(query)) < 2 then return; end if;
  perform public.check_rate_limit('dancer_search', 120, interval '10 minutes');
  return query
  select p.id, p.dancer_code, coalesce(p.name, p.full_name, 'Tanečník'), p.club, p.avatar_url
  from public.profiles p
  where (p.account_status is null or p.account_status = 'active')
    and (p.dancer_code ilike v_query || '%'
         or (coalesce(p.name, p.full_name) ilike '%' || v_query || '%'
             and p.birth_year <= extract(year from now())::int - 17))
    and not public.is_blocked_between(p.id, auth.uid())
  limit 10;
end;
$function$;
